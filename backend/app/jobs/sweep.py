"""Parameter sweep / 区间参数 expansion.

Only uniform simplex grid sampling is supported (kind:'simplex'): all lattice
points on the (n-1)-simplex at resolution T, generated by
nimplex.simplex_grid_fractional_py(n, T).  Use this for list[float] params
whose values must sum to 1 (e.g. weights).

Optional per-component bounds (`min`, `max` arrays of length n) filter out
lattice points that violate any component bound.  Defaults are 0 / 1.

Each child job consumes exactly one resolved dict via the existing runner
path, so this module has zero rasterio / FastAPI dependencies and is fully
unit-testable in isolation.
"""
from __future__ import annotations

import copy
import itertools
import math
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from ..algorithms.registry import AlgorithmInfo


MAX_SWEEP_SAMPLES = 200

# Floating-point slack when comparing nimplex k/T values against bounds.
_BOUND_TOL = 1e-9

# nimplex native extension lives in backend/vendor/nimplex.so
_VENDOR_DIR = Path(__file__).parent.parent.parent / "vendor"


def _nimplex():
    """Lazy-import nimplex from vendor/, raising ImportError with a clear message."""
    vendor = str(_VENDOR_DIR)
    if vendor not in sys.path:
        sys.path.insert(0, vendor)
    try:
        import nimplex as _nx  # noqa: PLC0415
        return _nx
    except ImportError as e:
        raise ImportError(
            f"nimplex.so not found in {_VENDOR_DIR}. "
            "Build it from https://github.com/amkrajewski/nimplex "
            "and copy nimplex.so into backend/vendor/."
        ) from e


@dataclass(frozen=True)
class SimplexSpec:
    """Uniform grid on the (n-1)-simplex via nimplex, with optional bounds.

    n_components: dimensionality (inferred from len(base_params[param_name])).
    n_divisions:  T — step = 1/T; unfiltered sample count = C(n + T - 1, T).
    min_bounds:   optional per-component lower bound (defaults to 0).
    max_bounds:   optional per-component upper bound (defaults to 1).
    When either bound is set, lattice points with any component outside its
    [min, max] interval are dropped.
    """
    n_components: int
    n_divisions: int
    min_bounds: tuple[float, ...] | None = None
    max_bounds: tuple[float, ...] | None = None


ParamRangeSpec = SimplexSpec


