@dataclass(frozen=True)
class _Axis:
    param: str
    samples: tuple[Any, ...]


def _parse_simplex(spec: dict, base_value: Any, name: str) -> SimplexSpec:
    if not isinstance(base_value, list) or len(base_value) < 2:
        raise ValueError(
            f"params['{name}'] must be a list of length >= 2 for kind='simplex'; "
            f"got {type(base_value).__name__ if not isinstance(base_value, list) else f'len={len(base_value)}'}"
        )
    raw_nd = spec.get("n_divisions")
    try:
        nd = int(raw_nd)
        if nd != raw_nd:  # catches floats like 4.5
            raise ValueError
    except (TypeError, ValueError):
        raise ValueError(
            f"param_ranges['{name}'].n_divisions must be a positive integer"
        )
    if nd < 1:
        raise ValueError(f"param_ranges['{name}'].n_divisions must be >= 1")

    n = len(base_value)
    min_bounds = _parse_bound_array(spec.get("min"), n, name, "min")
    max_bounds = _parse_bound_array(spec.get("max"), n, name, "max")

    # Per-component ordering and feasibility checks.
    lo = min_bounds if min_bounds is not None else (0.0,) * n
    hi = max_bounds if max_bounds is not None else (1.0,) * n
    for i, (a, b) in enumerate(zip(lo, hi)):
        if a > b + _BOUND_TOL:
            raise ValueError(
                f"param_ranges['{name}']: min[{i}]={a} > max[{i}]={b}"
            )
    if sum(lo) > 1.0 + _BOUND_TOL:
        raise ValueError(
            f"param_ranges['{name}']: sum(min)={sum(lo):g} > 1; no weight vector is feasible"
        )
    if sum(hi) < 1.0 - _BOUND_TOL:
        raise ValueError(
            f"param_ranges['{name}']: sum(max)={sum(hi):g} < 1; no weight vector is feasible"
        )

    return SimplexSpec(
        n_components=n,
        n_divisions=nd,
        min_bounds=min_bounds,
        max_bounds=max_bounds,
    )


def _parse_bound_array(
    raw: Any, n: int, name: str, which: str
) -> tuple[float, ...] | None:
    """Validate an optional `min`/`max` array. Returns None if raw is None."""
    if raw is None:
        return None
    if not isinstance(raw, list):
        raise ValueError(
            f"param_ranges['{name}'].{which} must be a list of {n} floats"
        )
    if len(raw) != n:
        raise ValueError(
            f"param_ranges['{name}'].{which} length {len(raw)} does not match "
            f"params['{name}'] length {n}"
        )
    out: list[float] = []
    for i, v in enumerate(raw):
        if not isinstance(v, (int, float)) or isinstance(v, bool):
            raise ValueError(
                f"param_ranges['{name}'].{which}[{i}] must be a number"
            )
        f = float(v)
        if f < -_BOUND_TOL or f > 1.0 + _BOUND_TOL:
            raise ValueError(
                f"param_ranges['{name}'].{which}[{i}]={f} must lie in [0, 1]"
            )
        out.append(max(0.0, min(1.0, f)))
    return tuple(out)


def _simplex_unfiltered_size(spec: SimplexSpec) -> int:
    """C(n + T - 1, T) — lattice point count before applying bounds."""
    return math.comb(spec.n_components + spec.n_divisions - 1, spec.n_divisions)


def _simplex_size(spec: SimplexSpec) -> int:
    """Exact post-filter sample count. Materializes the grid when bounds are set."""
    if spec.min_bounds is None and spec.max_bounds is None:
        return _simplex_unfiltered_size(spec)
    return len(_simplex_samples(spec))


def _simplex_samples(spec: SimplexSpec) -> tuple[tuple[float, ...], ...]:
    """Generate (and filter) lattice points. Each row sums to 1."""
    nx = _nimplex()
    grid = nx.simplex_grid_fractional_py(spec.n_components, spec.n_divisions)
    rows = (tuple(row) for row in grid)
    if spec.min_bounds is None and spec.max_bounds is None:
        return tuple(rows)
    lo = spec.min_bounds if spec.min_bounds is not None else (0.0,) * spec.n_components
    hi = spec.max_bounds if spec.max_bounds is not None else (1.0,) * spec.n_components
    return tuple(
        row for row in rows
        if all(lo[i] - _BOUND_TOL <= v <= hi[i] + _BOUND_TOL for i, v in enumerate(row))
    )


def _fmt(v: Any) -> str:
    """Compact numeric formatting for labels: '1' not '1.0', '0.25' not '0.250000'."""
    if isinstance(v, int):
        return str(v)
    if isinstance(v, float):
        if v.is_integer():
            return str(int(v))
        return f"{v:g}"
    return str(v)
