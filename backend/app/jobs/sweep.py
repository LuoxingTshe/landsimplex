def parse_param_ranges(
    raw: dict[str, Any],
    algo_info: AlgorithmInfo,
    base_params: dict[str, Any],
) -> dict[str, ParamRangeSpec]:
    """Validate and normalize a raw `param_ranges` payload into typed specs.

    Raises ValueError with a human-readable message for any validation failure.
    The API layer turns this into HTTP 400.
    """
    if not isinstance(raw, dict):
        raise ValueError("param_ranges must be an object")

    by_name = {p.name: p for p in algo_info.params}
    out: dict[str, ParamRangeSpec] = {}

    for name, spec in raw.items():
        if name not in by_name:
            raise ValueError(f"Unknown param '{name}' in param_ranges")
        pspec = by_name[name]
        if not pspec.sweepable:
            raise ValueError(f"Param '{name}' is not sweepable")
        if not isinstance(spec, dict) or "kind" not in spec:
            raise ValueError(f"param_ranges['{name}'] must be an object with a 'kind' field")

        kind = spec["kind"]
        if kind == "simplex":
            if pspec.type != "list[float]":
                raise ValueError(
                    f"Param '{name}' is {pspec.type!r}; only list[float] accepts kind='simplex'"
                )
            out[name] = _parse_simplex(spec, base_params.get(name), name)
        else:
            raise ValueError(
                f"param_ranges['{name}'].kind must be 'simplex'"
            )

    return out


def sweep_size(ranges: dict[str, ParamRangeSpec]) -> int:
    """Number of samples in the Cartesian product across all axes.

    When a SimplexSpec has bounds set, the grid is materialized and filtered
    to get the exact count; otherwise the closed-form binomial is used.
    """
    total = 1
    for spec in ranges.values():
        if isinstance(spec, SimplexSpec):
            total *= _simplex_size(spec)
    return total


def expand_ranges(
    base_params: dict[str, Any],
    ranges: dict[str, ParamRangeSpec],
    algo_info: AlgorithmInfo,
) -> list[tuple[dict[str, Any], str]]:
    """Expand sweep specs into a list of (resolved_params, sample_label).

    Axes are iterated in `algo_info.params` declaration order. This makes
    sample_index stable across submissions of the same shape.

    Raises ValueError if any simplex axis has bounds that eliminate every
    lattice point.
    """
    # 1. Collect axes in declaration order.
    axes: list[_Axis] = []
    for pspec in algo_info.params:
        if pspec.name not in ranges:
            continue
        spec = ranges[pspec.name]
        if isinstance(spec, SimplexSpec):
            samples = _simplex_samples(spec)
            if not samples:
                raise ValueError(
                    f"param_ranges['{pspec.name}']: bounds eliminate all "
                    f"{_simplex_unfiltered_size(spec)} lattice points"
                )
            axes.append(_Axis(param=pspec.name, samples=samples))

    if not axes:
        # Degenerate: no sweep declared. Return the single base case.
        return [(copy.deepcopy(base_params), "")]

    # 2. Cartesian product across all axes.
    out: list[tuple[dict[str, Any], str]] = []
    for combo in itertools.product(*(a.samples for a in axes)):
        resolved = copy.deepcopy(base_params)
        label_bits: list[str] = []
        for axis, value in zip(axes, combo):
            resolved[axis.param] = list(value)
            label_bits.append(
                f"{axis.param}=[{','.join(_fmt(v) for v in value)}]"
            )
        out.append((resolved, "_".join(label_bits)))

    return out


def format_combo_suffix(label_bits: list[str]) -> str:
    """Join label fragments with '_' and truncate ultra-long labels."""
    s = "_".join(label_bits)
    if len(s) > 80:
        s = s[:38] + "..." + s[-38:]
    return s


